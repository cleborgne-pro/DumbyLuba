#!/usr/bin/env python3
"""Generates the embedded Mammotion error-code table (English and French).

Source: PyMammotion (GPL-3.0), pymammotion/data/error_codes.csv, commit pinned below.
English: the en_implication / en_solution columns, as published upstream (every code has an English label).
French label: the fr_implication column, replaced by tools/robot-error-codes-fr.tsv when it is missing or
inaccurate. French solution: only the fr_solution column (otherwise the app shows a French action per category).
Other languages of the source file are not embedded.

Usage:
  mkdir -p /tmp/pymammotion-errors
  curl -sfL -o /tmp/pymammotion-errors/error_codes.csv \
    https://raw.githubusercontent.com/mikey0000/PyMammotion/<COMMIT>/pymammotion/data/error_codes.csv
  python3 -I tools/build-robot-error-codes.py /tmp/pymammotion-errors/error_codes.csv
"""
import csv
import hashlib
import pathlib
import sys

COMMIT = "967c7ac9bc67b11b5d883700b0380fa29ae8f5e4"
SHA256 = "4ece724b92cbbe493436458e9ffd15fb9930f604e1794161ae7ed413f9ad7f5d"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OVERRIDES = ROOT / "tools" / "robot-error-codes-fr.tsv"
OUTPUT = ROOT / "app" / "src" / "main" / "resources" / "fr" / "luba" / "poc" / "protocol" / "robot_error_codes.tsv"


def clean(text: str) -> str:
    # Zero-width characters found in some upstream English solutions are dropped.
    return " ".join(text.translate({0x200B: None, 0x200C: None, 0x200D: None, 0xFEFF: None}).split())


def main(source: str) -> None:
    raw = pathlib.Path(source).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        sys.exit(f"Unexpected SHA-256 {digest}: update COMMIT/SHA256 after review")
    overrides = {}
    for line in OVERRIDES.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        code, label = line.split("\t", 1)
        overrides[int(code)] = clean(label)
    rows = []
    for row in csv.DictReader(raw.decode("utf-8").splitlines()):
        code = abs(int(row["code"]))
        label_en = clean(row["en_implication"])
        if not label_en:
            sys.exit(f"Code {code} without an English label in the source")
        label_fr = overrides.get(code) or clean(row["fr_implication"])
        if not label_fr:
            sys.exit(f"Code {code} without a French label: complete {OVERRIDES.name}")
        rows.append((code, clean(row["module"]), clean(row["level"]), label_en, clean(row["en_solution"]),
                     label_fr, clean(row["fr_solution"])))
    unused = set(overrides) - {r[0] for r in rows}
    if unused:
        sys.exit(f"Translations without a source code: {sorted(unused)}")
    rows.sort()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as out:
        out.write(f"# Mammotion error codes — PyMammotion {COMMIT} (GPL-3.0), English and French. "
                  "Generated by tools/build-robot-error-codes.py\n")
        out.write("# code\tmodule\tlevel\tlabel_en\tsolution_en\tlabel_fr\tsolution_fr\n")
        for row in rows:
            out.write("\t".join(str(v) for v in row) + "\n")
    print(f"{len(rows)} codes written to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
